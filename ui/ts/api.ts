/* ============================================================================
   API catalog page — every Python endpoint, rendered from ui/endpoints.json
   (generated by scripts/build-ui straight from loco/server.py's dispatch, so
   the catalog cannot drift). Includes a live try-it console: pick a route,
   edit the body, fire it, read the reply.
   ========================================================================== */

interface EpRoute {
  method: string;
  path: string;
  group: string;
  desc: string;
  kind: string;          // "http" | "ws"
  examplePath: string;
  exampleBody: any;
}

interface EpGroup { id: string; title: string; routes: EpRoute[] }
interface EpCatalog { source: string; count: number; groups: EpGroup[] }

let catalog: EpCatalog | null = null;
const flat = new Map<string, EpRoute>();      // "METHOD path" → route
let selectedKey = "";
let wsLogOn = false;
const wsLines: string[] = [];

const $ep = (sel: string) => document.querySelector(sel) as HTMLElement | null;

/* ------------------------------------------------------------ rendering -- */
function epRow(r: EpRoute): string {
  const m = r.method.toLowerCase();
  const cls = r.method === "GET" ? "get" : r.method === "POST" ? "post" : "ws";
  const pathHtml = esc(r.path).replace(/\{([^}]+)\}/g, '<span class="ph">{$1}</span>');
  return `<div class="ep" data-key="${esc(r.method)} ${esc(r.path)}">
    <span class="method ${cls}">${r.kind === "ws" ? "WS" : r.method}</span>
    <span class="path">${pathHtml}</span>
    <span class="desc">${esc(r.desc)}</span>
    <span class="go">try →</span>
  </div>`;
}

function renderCatalog(): void {
  const box = $ep("#epList");
  if (!box || !catalog) return;
  const q = (($ep("#epSearch") as HTMLInputElement | null)?.value || "").trim().toLowerCase();
  let shown = 0;
  box.innerHTML = catalog.groups
    .map((g) => {
      const routes = g.routes.filter(
        (r) =>
          !q ||
          r.path.toLowerCase().includes(q) ||
          r.desc.toLowerCase().includes(q) ||
          r.method.toLowerCase() === q ||
          g.title.toLowerCase().includes(q)
      );
      if (!routes.length) return "";
      shown += routes.length;
      return `<div class="ep-group">
        <div class="ep-gname">${esc(g.title)}<span class="cnt">${routes.length}</span></div>
        ${routes.map(epRow).join("")}
      </div>`;
    })
    .join("");

  const cnt = $ep("#epCount");
  if (cnt) cnt.textContent = `${shown} / ${catalog.count} routes`;

  box.querySelectorAll<HTMLElement>(".ep").forEach((el) =>
    el.addEventListener("click", () => selectRoute(el.dataset.key || ""))
  );
}

/* --------------------------------------------------------------- console - */
function selectRoute(key: string): void {
  const r = flat.get(key);
  if (!r) return;
  selectedKey = key;
  document.querySelectorAll<HTMLElement>(".ep").forEach((el) =>
    el.classList.toggle("sel", (el.dataset.key || "") === key)
  );

  const badge = $ep("#cMethod");
  if (badge) {
    badge.textContent = r.kind === "ws" ? "WS" : r.method;
    badge.className = "method " + (r.method === "GET" ? "get" : r.method === "POST" ? "post" : "ws");
  }
  const pathEl = $ep("#cPath") as HTMLInputElement | null;
  if (pathEl) pathEl.value = r.examplePath || r.path;
  const bodyEl = $ep("#cBody") as HTMLTextAreaElement | null;
  if (bodyEl) bodyEl.value = r.exampleBody != null ? JSON.stringify(r.exampleBody, null, 2) : "";
  const descEl = $ep("#cDesc");
  if (descEl) descEl.textContent = r.desc;

  wsLogOn = r.kind === "ws";
  const send = $ep("#cSend") as HTMLButtonElement | null;
  if (send) {
    send.disabled = wsLogOn;
    send.textContent = wsLogOn ? "live feed below" : "Send";
  }
  set_status("idle", wsLogOn ? "streaming · ws" : "ready");
  const out = $ep("#cOut");
  if (out) {
    out.textContent = wsLogOn
      ? (wsLines.length ? wsLines.join("\n") : "waiting for events — send a chat message from another tab to see routes appear…")
      : "response appears here…";
    if (wsLogOn) out.scrollTop = out.scrollHeight;
  }
}

function set_status(kind: "idle" | "ok" | "err", text: string): void {
  const el = $ep("#cStatus");
  if (!el) return;
  el.innerHTML = `<span class="st ${kind}">${esc(text)}</span>`;
}

async function sendRequest(): Promise<void> {
  const r = flat.get(selectedKey);
  if (!r || wsLogOn) return;
  const pathEl = $ep("#cPath") as HTMLInputElement | null;
  const bodyEl = $ep("#cBody") as HTMLTextAreaElement | null;
  const out = $ep("#cOut");
  const target = (pathEl?.value || r.path).trim();
  const bodyText = (bodyEl?.value || "").trim();

  set_status("idle", "running…");
  if (out) out.textContent = "…";
  const t0 = performance.now();

  let resp: Response;
  try {
    const init: RequestInit = { method: r.method };
    if (r.method !== "GET" && bodyText) {
      init.headers = { "Content-Type": "application/json" };
      init.body = bodyText;
    }
    resp = await fetch(target, init);
  } catch (e) {
    set_status("err", "network error");
    if (out) out.textContent = String(e);
    return;
  }

  const ms = Math.round(performance.now() - t0);
  const text = await resp.text();
  let pretty = text;
  try { pretty = JSON.stringify(JSON.parse(text), null, 2); } catch { /* raw */ }

  set_status(resp.ok ? "ok" : "err", `${resp.status} ${resp.statusText || ""} · ${ms} ms · ${text.length} B`.trim());
  if (out) {
    out.textContent = pretty || "(empty body)";
    out.scrollTop = 0;
  }
}

/* ---------------------------------------------------------------- boot --- */
document.addEventListener("DOMContentLoaded", async () => {
  const search = $ep("#epSearch") as HTMLInputElement | null;
  search?.addEventListener("input", renderCatalog);

  ($ep("#cSend") as HTMLButtonElement | null)?.addEventListener("click", sendRequest);
  ($ep("#cBody") as HTMLTextAreaElement | null)?.addEventListener("keydown", (e) => {
    const ev = e as KeyboardEvent;
    if ((ev.ctrlKey || ev.metaKey) && ev.key === "Enter") { ev.preventDefault(); sendRequest(); }
  });

  /* live WS monitor: while /ws is selected, stream raw events into the console */
  onWs((msg) => {
    if (!wsLogOn) return;
    const out = $ep("#cOut");
    if (!out) return;
    const line = `${clockOf(msg.ts || Date.now() / 1000)}  ${JSON.stringify(msg)}`;
    wsLines.push(line);
    if (wsLines.length > 120) wsLines.shift();
    out.textContent = wsLines.join("\n");
    out.scrollTop = out.scrollHeight;
  });

  try {
    const resp = await fetch("/ui/endpoints.json");
    const data = await resp.json();
    if (!data || !Array.isArray(data.groups)) throw new Error("unexpected catalog shape");
    catalog = data as EpCatalog;
    for (const g of catalog.groups) for (const r of g.routes) flat.set(`${r.method} ${r.path}`, r);
    const gen = $ep("#epSource");
    if (gen) gen.textContent = `${catalog.count} routes · ${catalog.source}`;
    renderCatalog();
    const first = flat.get("GET /health");
    if (first) selectRoute(`GET ${first.path}`);
  } catch (e) {
    const box = $ep("#epList");
    if (box) {
      box.innerHTML = `<div class="card"><h3>catalog unavailable</h3>
        <p>Could not load <code>/ui/endpoints.json</code> — rebuild it with
        <code>node scripts/build-ui</code>. (${esc(String(e))})</p></div>`;
    }
  }
});
